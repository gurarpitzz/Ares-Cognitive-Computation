"""GPU telemetry and thermal throttle detection for ARES experiments."""

from pathlib import Path
from typing import Optional, Tuple
import pandas as pd


def detect_throttle(
    csv_path: Path,
    temp_threshold_c: float = 87.0,
    clock_drop_ratio: float = 0.80,
    min_throttle_minutes: float = 5.0
) -> Tuple[bool, str]:
    """Analyze GPU telemetry CSV to detect thermal throttling events.
    
    Args:
        csv_path: Path to the telemetry CSV generated by nvidia-smi.
        temp_threshold_c: Temperature threshold in Celsius.
        clock_drop_ratio: Drop ratio relative to median clock.
        min_throttle_minutes: Minimum consecutive duration to flag as throttling.
        
    Returns:
        (is_throttled, reason_string)
    """
    if not csv_path.exists():
        return False, "Telemetry file does not exist"
        
    try:
        # Expected columns: timestamp, temperature.gpu, clocks.sm [MHz], power.draw [W], utilization.gpu [%], memory.used [MiB]
        df = pd.read_csv(csv_path, skipinitialspace=True)
        # Clean column names (strip units like [MHz])
        df.columns = [c.split()[0].replace(".", "_") for c in df.columns]
        
        temp_col = "temperature_gpu"
        clock_col = "clocks_sm"
        
        if temp_col not in df.columns or clock_col not in df.columns:
            return False, "Missing required telemetry columns"
            
        # Parse numeric values
        temps = pd.to_numeric(df[temp_col].astype(str).str.extract(r"(\d+[\.]?\d*)")[0], errors="coerce")
        clocks = pd.to_numeric(df[clock_col].astype(str).str.extract(r"(\d+[\.]?\d*)")[0], errors="coerce")
        
        median_clock = clocks.median()
        if pd.isna(median_clock) or median_clock == 0:
            return False, "Invalid clock readings"
            
        throttled_mask = (temps >= temp_threshold_c) & (clocks < clock_drop_ratio * median_clock)
        
        # Check for consecutive throttled readings (assuming 30s intervals)
        intervals_per_min = 2  # 30s intervals
        required_consecutive = int(min_throttle_minutes * intervals_per_min)
        
        consecutive = 0
        max_consecutive = 0
        for is_th in throttled_mask:
            if is_th:
                consecutive += 1
                max_consecutive = max(max_consecutive, consecutive)
            else:
                consecutive = 0
                
        if max_consecutive >= required_consecutive:
            duration_mins = max_consecutive * 0.5
            return True, f"Thermal throttle detected: {duration_mins:.1f} mins at >= {temp_threshold_c}°C with clock < {clock_drop_ratio * 100:.0f}% median."
            
        return False, "No thermal throttling detected."
        
    except Exception as e:
        return False, f"Failed to parse telemetry: {e}"
