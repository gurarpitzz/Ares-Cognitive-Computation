def export_table_latex_and_csv(table_name: str, data: list, output_dir: str):
    """Exports dataset to both CSV and publication-ready LaTeX booktabs."""
    os.makedirs(os.path.join(output_dir, "tables"), exist_ok=True)
    csv_path = os.path.join(output_dir, "tables", f"{table_name}.csv")
    tex_path = os.path.join(output_dir, "tables", f"{table_name}.tex")
    
    if not data:
        return
        
    keys = list(data[0].keys())
    
    # Write CSV
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        writer.writerows(data)
        
    # Write LaTeX Booktabs
    col_spec = "l" + "c" * (len(keys) - 1)
    headers = [k.replace("_", " ").title() for k in keys]
    
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write("% Auto-generated by ARES 2.0 Table Engine (Milestone M15)\n")
        f.write("\\begin{table*}[t]\n")
        f.write("  \\centering\n")
        f.write("  \\small\n")
        f.write(f"  \\caption{{Empirical Evaluation for {table_name.replace('_', ' ').title()}}}\n")
        f.write(f"  \\label{{tab:{table_name}}}\n")
        f.write(f"  \\begin{{tabular}}{{{col_spec}}}\n")
        f.write("    \\toprule\n")
        f.write("    " + " & ".join([f"\\textbf{{{h}}}" for h in headers]) + " \\\\\n")
        f.write("    \\midrule\n")
        for row in data:
            vals = [str(row[k]) for k in keys]
            f.write("    " + " & ".join(vals) + " \\\\\n")
        f.write("    \\bottomrule\n")
        f.write("  \\end{tabular}\n")
        f.write("\\end{table*}\n")
        
    logger.info("Exported %s to CSV and LaTeX (%s)", table_name, tex_path)


def run_make_tables(output_dir: str):
    """Runs all table generation routines."""
    export_table_latex_and_csv("table07_calibrated_track_metrics", TABLE_07_DATA, output_dir)
    export_table_latex_and_csv("table08_cross_domain_generalization", TABLE_08_DATA, output_dir)


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--output_dir", default="milestones/M15_release")
    args = parser.parse_args()
    run_make_tables(args.output_dir)
